//! An in-memory, caller-bound authorization interaction table.
use std::{collections::HashMap, sync::Mutex};

use url::Url;

use super::{secure_url, Callback};

const MAX_ATTEMPTS: usize = 32;
const MAX_LIFETIME_MS: u64 = 600_000;
const MAX_CALLBACK_BYTES: usize = 8192;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Error {
    Access,
    Invalid,
    Conflict,
    Closed,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum State {
    Starting,
    AwaitingCallback,
    AwaitingDevice,
    Exchanging,
    Authorized,
    Failed,
    Cancelled,
    Expired,
}

impl State {
    fn active(self) -> bool {
        matches!(
            self,
            Self::Starting | Self::AwaitingCallback | Self::AwaitingDevice | Self::Exchanging
        )
    }
}

#[derive(Clone)]
pub struct View {
    pub id: String,
    pub server: String,
    pub state: State,
    pub expires_ms: u64,
}

struct Attempt {
    owner: String,
    view: View,
    redirect: Url,
}

#[derive(Default)]
struct Entries {
    by_id: HashMap<String, Attempt>,
    closed: bool,
}

#[derive(Default)]
pub struct Attempts {
    entries: Mutex<Entries>,
}

impl Attempts {
    /// The authority and opaque ID have been verified/generated by the host.
    pub fn start(
        &self,
        id: &str,
        owner: &str,
        server: &str,
        redirect: &str,
        now_ms: u64,
        lifetime_ms: u64,
    ) -> Result<View, Error> {
        if [id, owner, server].into_iter().any(|value| {
            value.is_empty() || value.len() > 256 || value.chars().any(char::is_control)
        }) || !(1..=MAX_LIFETIME_MS).contains(&lifetime_ms)
        {
            return Err(Error::Invalid);
        }
        let redirect = secure_url(redirect).map_err(|_| Error::Invalid)?;
        let mut entries = self.entries.lock().map_err(|_| Error::Closed)?;
        if entries.closed {
            return Err(Error::Closed);
        }
        entries
            .by_id
            .retain(|_, attempt| attempt.view.expires_ms > now_ms);
        if entries.by_id.len() == MAX_ATTEMPTS
            || entries.by_id.contains_key(id)
            || entries
                .by_id
                .values()
                .any(|attempt| attempt.view.server == server && attempt.view.state.active())
        {
            return Err(Error::Conflict);
        }
        let view = View {
            id: id.to_owned(),
            server: server.to_owned(),
            state: State::Starting,
            expires_ms: now_ms.checked_add(lifetime_ms).ok_or(Error::Invalid)?,
        };
        entries.by_id.insert(
            id.to_owned(),
            Attempt {
                owner: owner.to_owned(),
                view: view.clone(),
                redirect,
            },
        );
        Ok(view)
    }

    pub fn status(&self, id: &str, owner: &str, now_ms: u64) -> Result<View, Error> {
        self.owned(id, owner, now_ms, |attempt| Ok(attempt.view.clone()))
    }

    pub fn awaiting(
        &self,
        id: &str,
        owner: &str,
        now_ms: u64,
        device: bool,
    ) -> Result<View, Error> {
        self.owned(id, owner, now_ms, |attempt| {
            if attempt.view.state != State::Starting {
                return Err(Error::Conflict);
            }
            attempt.view.state = if device {
                State::AwaitingDevice
            } else {
                State::AwaitingCallback
            };
            Ok(attempt.view.clone())
        })
    }

    /// Accept a single callback for this actor and return it to the worker.
    /// The flow then checks the callback state and issuer before token exchange.
    pub fn submit(
        &self,
        id: &str,
        owner: &str,
        now_ms: u64,
        callback: &str,
    ) -> Result<Callback, Error> {
        self.owned(id, owner, now_ms, |attempt| {
            if attempt.view.state != State::AwaitingCallback {
                return Err(Error::Conflict);
            }
            if callback.len() > MAX_CALLBACK_BYTES {
                return Err(Error::Invalid);
            }
            let callback = secure_url(callback).map_err(|_| Error::Invalid)?;
            if callback.origin() != attempt.redirect.origin()
                || callback.path() != attempt.redirect.path()
            {
                return Err(Error::Invalid);
            }
            let pairs: Vec<_> = callback.query_pairs().collect();
            for (key, value) in attempt.redirect.query_pairs() {
                if !pairs.contains(&(key, value)) {
                    return Err(Error::Invalid);
                }
            }
            let field = |key: &str| -> Result<Option<String>, Error> {
                let mut found = pairs.iter().filter(|(name, _)| name == key);
                let value = found.next().map(|(_, value)| value.to_string());
                if found.next().is_some() {
                    Err(Error::Invalid)
                } else {
                    Ok(value)
                }
            };
            let code = field("code")?
                .filter(|value| !value.is_empty())
                .ok_or(Error::Invalid)?;
            let state = field("state")?
                .filter(|value| !value.is_empty())
                .ok_or(Error::Invalid)?;
            let issuer = field("iss")?;
            attempt.view.state = State::Exchanging;
            Ok(Callback::new(code, state, issuer))
        })
    }

    pub fn finish(
        &self,
        id: &str,
        owner: &str,
        now_ms: u64,
        authorized: bool,
    ) -> Result<View, Error> {
        self.owned(id, owner, now_ms, |attempt| {
            if !attempt.view.state.active()
                || authorized
                    && !matches!(
                        attempt.view.state,
                        State::Exchanging | State::AwaitingDevice
                    )
            {
                return Err(Error::Conflict);
            }
            attempt.view.state = if authorized {
                State::Authorized
            } else {
                State::Failed
            };
            Ok(attempt.view.clone())
        })
    }

    pub fn cancel(&self, id: &str, owner: &str, now_ms: u64) -> Result<View, Error> {
        self.owned(id, owner, now_ms, |attempt| {
            if attempt.view.state.active() {
                attempt.view.state = State::Cancelled;
            }
            Ok(attempt.view.clone())
        })
    }

    pub fn close(&self) -> Result<(), Error> {
        let mut entries = self.entries.lock().map_err(|_| Error::Closed)?;
        entries.closed = true;
        entries.by_id.clear();
        Ok(())
    }

    fn owned<T>(
        &self,
        id: &str,
        owner: &str,
        now_ms: u64,
        apply: impl FnOnce(&mut Attempt) -> Result<T, Error>,
    ) -> Result<T, Error> {
        let mut entries = self.entries.lock().map_err(|_| Error::Closed)?;
        if entries.closed {
            return Err(Error::Closed);
        }
        let attempt = entries
            .by_id
            .get_mut(id)
            .filter(|attempt| attempt.owner == owner)
            .ok_or(Error::Access)?;
        if attempt.view.state.active() && now_ms >= attempt.view.expires_ms {
            attempt.view.state = State::Expired;
        }
        apply(attempt)
    }
}
