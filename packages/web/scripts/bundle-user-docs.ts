import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = (p: string): string => fileURLToPath(new URL(p, import.meta.url));
const userDocsDir = resolve(here("../../../docs/user"));
const outDir = resolve(here("../src/pages/help/docs-bundle"));

function readDocs(lang: "de" | "en"): void {
  const dir = join(userDocsDir, lang);
  const files = readdirSync(dir).filter((f) => f.endsWith(".md")).sort();
  const index: { slug: string; title: string }[] = [];
  mkdirSync(join(outDir, lang), { recursive: true });

  for (const f of files) {
    const slug = f.replace(/\.md$/, "");
    const raw = readFileSync(join(dir, f), "utf8");
    const titleMatch = raw.match(/^#\s+(.+)$/m);
    const title = titleMatch && titleMatch[1] ? titleMatch[1].trim() : slug;
    index.push({ slug, title });

    // Write separate file for each document to keep chunks well under 12 KiB budget
    const pageCode = `import "../../../../styles/help.css";
export const doc = ${JSON.stringify({ slug, title, content: raw })};\n`;
    writeFileSync(join(outDir, lang, `${slug}.ts`), pageCode, "utf8");
  }

  // Write loader index
  const loaderCases = index
    .map(
      (item) =>
        `    case ${JSON.stringify(item.slug)}: return import("./${lang}/${item.slug}.ts").then(m => m.doc);`,
    )
    .join("\n");

  const indexCode = `// Auto-generated by scripts/bundle-user-docs.mjs. Do not edit directly.
export const DOCS_INDEX: readonly { slug: string; title: string }[] = ${JSON.stringify(index, null, 2)};

export async function loadDoc(slug: string): Promise<{ slug: string; title: string; content: string } | null> {
  switch (slug) {
${loaderCases}
    default: return null;
  }
}
`;
  writeFileSync(join(outDir, `${lang}-index.ts`), indexCode, "utf8");
}

export function bundleDocs(): void {
  mkdirSync(outDir, { recursive: true });
  readDocs("de");
  readDocs("en");
  console.log("Bundled docs/user into packages/web/src/pages/help/docs-bundle/{de,en}/*");
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  bundleDocs();
}
