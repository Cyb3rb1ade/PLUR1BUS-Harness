import { existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = (p: string): string => fileURLToPath(new URL(p, import.meta.url));
const defaultUserDocsDir = resolve(here("../../../docs/user"));
const defaultOutDir = resolve(here("../src/pages/help/docs-bundle"));

export interface BundleDirs { userDocsDir?: string; outDir?: string }

/** Pure render: relative output path (posix) -> file content. No filesystem writes. */
export function renderBundle(userDocsDir: string = defaultUserDocsDir): Map<string, string> {
  const out = new Map<string, string>();
  for (const lang of ["de", "en"] as const) {
    const dir = join(userDocsDir, lang);
    const files = readdirSync(dir).filter((f) => f.endsWith(".md")).sort();
    const index: { slug: string; title: string }[] = [];

    for (const f of files) {
      const slug = f.replace(/\.md$/, "");
      const raw = readFileSync(join(dir, f), "utf8");
      const titleMatch = raw.match(/^#\s+(.+)$/m);
      const title = titleMatch && titleMatch[1] ? titleMatch[1].trim() : slug;
      index.push({ slug, title });

      // Separate file per document to keep chunks well under 12 KiB budget
      out.set(`${lang}/${slug}.ts`, `import "../../../../styles/help.css";
export const doc = ${JSON.stringify({ slug, title, content: raw })};\n`);
    }

    const loaderCases = index
      .map(
        (item) =>
          `    case ${JSON.stringify(item.slug)}: return import("./${lang}/${item.slug}.ts").then(m => m.doc);`,
      )
      .join("\n");

    out.set(`${lang}-index.ts`, `// Auto-generated by scripts/bundle-user-docs.mjs. Do not edit directly.
export const DOCS_INDEX: readonly { slug: string; title: string }[] = ${JSON.stringify(index, null, 2)};

export async function loadDoc(slug: string): Promise<{ slug: string; title: string; content: string } | null> {
  switch (slug) {
${loaderCases}
    default: return null;
  }
}
`);
  }
  return out;
}

function listBundleFiles(outDir: string): string[] {
  const found: string[] = [];
  for (const lang of ["de", "en"]) {
    const d = join(outDir, lang);
    if (existsSync(d)) for (const f of readdirSync(d)) if (f.endsWith(".ts")) found.push(`${lang}/${f}`);
    if (existsSync(join(outDir, `${lang}-index.ts`))) found.push(`${lang}-index.ts`);
  }
  return found;
}

/** Compare the committed bundle with freshly rendered output. Never writes. Returns problem lines (empty = in sync). */
export function checkBundle({ userDocsDir = defaultUserDocsDir, outDir = defaultOutDir }: BundleDirs = {}): string[] {
  const expected = renderBundle(userDocsDir);
  const problems: string[] = [];
  for (const [rel, content] of expected) {
    const p = join(outDir, rel);
    if (!existsSync(p)) problems.push(`missing: ${rel}`);
    else if (readFileSync(p, "utf8") !== content) problems.push(`differs: ${rel}`);
  }
  for (const rel of listBundleFiles(outDir)) if (!expected.has(rel)) problems.push(`stale (no source doc): ${rel}`);
  return problems.sort();
}

export function bundleDocs({ userDocsDir = defaultUserDocsDir, outDir = defaultOutDir }: BundleDirs = {}): void {
  const expected = renderBundle(userDocsDir);
  for (const rel of listBundleFiles(outDir)) if (!expected.has(rel)) rmSync(join(outDir, rel));
  for (const [rel, content] of expected) {
    const p = join(outDir, rel);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content, "utf8");
  }
  console.log("Bundled docs/user into packages/web/src/pages/help/docs-bundle/{de,en}/*");
}

// Node resolves module symlinks, including macOS /var -> /private/var; compare canonical paths on both sides.
if (process.argv[1] && realpathSync(resolve(process.argv[1])) === realpathSync(fileURLToPath(import.meta.url))) {
  if (process.argv.includes("--check")) {
    const problems = checkBundle();
    if (problems.length > 0) {
      console.error("Help docs bundle is out of date relative to docs/user:");
      for (const p of problems) console.error(`  ${p}`);
      console.error("Run: node --experimental-strip-types packages/web/scripts/bundle-user-docs.ts");
      process.exit(1);
    }
    console.log("Help docs bundle is up to date.");
  } else {
    bundleDocs();
  }
}
