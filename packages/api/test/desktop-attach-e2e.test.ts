import test from "node:test";
import assert from "node:assert/strict";
import { generateKeyPairSync, randomBytes } from "node:crypto";
import { mkdtempSync, writeFileSync, rmSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { defaults } from "@plur1bus/config-schema";
import { connect } from "@plur1bus/module-api";
import { createCore } from "../../core/src/core.ts";
import { flatTestInternals } from "../../core/test/helpers/flat-embedder.ts";
import { createCoreLink } from "../src/core-link.ts";
import { createApiServer } from "../src/server.ts";
import { memoryAuditSink } from "../src/rbac-bridge.ts";

test("real Core/API: native code → device token → origin-bound one-use ticket → scoped SPA cookie → device/user revocation", {timeout:60000}, async t=>{
 const home=mkdtempSync(join(tmpdir(),"desktop-http-")),cfg=defaults();cfg.agents.main={};
 cfg.engine={neo:{enabled:false},gc:{enabled:false},obsidianBridge:{enabled:false},merging:{enabled:false},dreaming:{enabled:false},skillMiner:{enabled:false},temporalContext:{enabled:false},conversationReactivationRecall:{enabled:false},reranker:{enabled:false}};
 writeFileSync(join(home,"config.json"),JSON.stringify(cfg));
 const core=createCore({home,testInternals:flatTestInternals()});await core.start();
 const local=await connect({address:core.address,token:core.token,expectedServerPid:process.pid}),link=createCoreLink(home);
 const audit=memoryAuditSink(),logs:string[]=[];const log=(msg:string,f?:object)=>logs.push(JSON.stringify({msg,f}));
 const api=createApiServer({core:link,ownerToken:randomBytes(32).toString("hex"),audit,logger:{info:log,warn:log,debug:log,error:log},rateClasses:{auth:{capacity:100,refillPerSec:100},read:{capacity:100,refillPerSec:100},write:{capacity:100,refillPerSec:100}}});
 link.subscribePeople(id=>api.rightsChanged(id));const {url}=await api.listen();
 t.after(async()=>{await api.close();await link.close();await local.close();await core.stop({budgetMs:5000});rmSync(home,{recursive:true,force:true});});
 const post=(path:string,body:object,headers:Record<string,string>={})=>fetch(url+path,{method:"POST",headers:{"content-type":"application/json",...headers},body:JSON.stringify(body)});
 const meta=await fetch(url+"/api/v1/meta");assert.equal(meta.status,200);assert.deepEqual(Object.keys(await meta.json() as object).sort(),["capabilities","pairingRequired","version"]);assert.ok(meta.headers.get("content-security-policy"));
 const grant=await local.call<any>("device.pair",{kind:"desktop"});
 const publicKey=generateKeyPairSync("ed25519").publicKey.export({type:"spki",format:"der"}).toString("base64");
 const pairBody={code:grant.code,kind:"desktop",name:"My desktop",publicKey};
 const paired=await post("/api/v1/desktop/pair",pairBody);assert.equal(paired.status,200,await paired.clone().text());const device=await paired.json() as any;
 assert.equal((await post("/api/v1/desktop/pair",pairBody)).status,403);
 assert.equal((await post("/api/v1/desktop/redeem",{token:device.token,origin:"https://evil.example"})).status,403);
 const ticket=await (await post("/api/v1/desktop/redeem",{token:device.token,origin:url})).json() as any;
 const ticketBody={ticket:ticket.ticket,deviceId:device.device.id};
 const signed=await post("/api/v1/desktop/ticket",ticketBody,{origin:url});assert.equal(signed.status,200,await signed.clone().text());
 const cookie=signed.headers.get("set-cookie")!.split(";")[0]!;assert.match(signed.headers.get("set-cookie")!,/HttpOnly; SameSite=Strict/);
 assert.equal((await post("/api/v1/desktop/ticket",ticketBody,{origin:url})).status,401);
 assert.equal((await fetch(url+"/api/v1/whoami",{headers:{cookie}})).status,200);
 const csrf=async()=> (await (await fetch(url+"/api/v1/csrf",{headers:{cookie}})).json() as any).token;
 const denied=await post("/rpc",{jsonrpc:"2.0",id:1,method:"secret.list",params:{}},{cookie,"x-csrf-token":await csrf()});assert.equal(denied.status,200);assert.equal((await denied.json() as any).error.data.reason,"device-scope");
 const chats=await fetch(url+"/api/v1/chats",{headers:{cookie}});assert.equal(chats.status,200,await chats.clone().text());
 await local.call("device.revoke",{id:device.device.id});
 assert.equal((await fetch(url+"/api/v1/whoami",{headers:{cookie}})).status,401);
 assert.equal((await post("/api/v1/desktop/redeem",{token:device.token,origin:url})).status,403);
 const text=logs.join("\n")+JSON.stringify(audit.events)+readFileSync(join(home,"logs","audit.log"),"utf8");
 for(const secret of [grant.code,device.token,ticket.ticket])assert.ok(!text.includes(secret));
});
