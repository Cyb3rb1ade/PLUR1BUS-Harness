test("role RPC exercises real Engine embedding/reranking through host ports and safely reports host denials", async t => {
  let allowed = true, calls = 0;
  const server = http.createServer(async (req, res) => {
    calls++;
    assert.equal(req.headers.authorization, "Bearer fixture-key");
    let body = ""; for await (const chunk of req) body += chunk;
    res.setHeader("content-type", "application/json");
    if (req.url === "/v1/embeddings") res.end(JSON.stringify({ data: [{ index: 0, embedding: [1, 0, 0] }] }));
    else res.end('[{"index":0,"score":0.9},{"index":1,"score":0.1}]');
  }).listen(0, "127.0.0.1");
  await once(server, "listening");
  t.after(() => new Promise<void>(resolve => { server.closeAllConnections(); server.close(() => resolve()); }));
  const url = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
  const cfg = defaults(), l = layout(tempDir("p1b-role-test-")); mkdirSync(l.state, { recursive: true });
  cfg.engine.embedding = { provider: "openai-compatible", model: "fixture-embedding", baseUrl: `${url}/v1`, dimensions: 3, apiKeyRef: "fixture" };
  cfg.engine.reranker = { provider: "remote", model: "fixture-reranker", protocol: "tei", baseUrl: url, apiKeyRef: "fixture" };
  const config = buildEngineConfig(cfg, l);
  const logger = createLogger({ file: l.logFile("core"), level: "info", role: "core" }); t.after(() => logger.close());
  const secrets = createSecretStore({ keyring: createMemoryBackend(), file: createMemoryBackend(), fileFallback: () => false, audit: createMemoryAuditSink() });
  await secrets.set({ kind: "owner" }, "fixture", "fixture-key");
  const egress = createEgress({ config: () => ({ allowHosts: allowed ? ["127.0.0.1"] : [], allowPorts: Array.from({ length: 65535 }, (_, i) => i + 1), allowLoopback: allowed }) });
  const diagnostics = createEngineTestDiagnostics();
  const host = createHarnessHost({ layout: l, logger, config: cfg, engineConfig: config, agents: createAgentRegistry(cfg, l), events() {}, egress, secrets, onPortFailure: diagnostics.observe });
  const engine = bindEngine(host, config); t.after(() => engine.close({ budgetMs: 1000 }));
  const original = globalThis.fetch; globalThis.fetch = async () => { throw new Error("unexpected global fetch"); }; t.after(() => { globalThis.fetch = original; });
  const methods = guardMethods(buildEngineTestSurface({ embedding: engine.embedding, config: () => config, diagnostics }), { resolve: () => ({ kind: "person", role: "admin", userId: "fixture" }), audit: memoryAuditSink(), now: Date.now });
  const call = (role: string) => methods["admin.engine.test"]!({ role }, { requestId: "probe", connectionId: "fixture", signal: new AbortController().signal }) as Promise<any>;
  const embed = await call("embedder"); assert.equal(embed.ok, true); assert.equal(embed.dimensions, 3); assert.equal(embed.model, "fixture-embedding");
  const rerank = await call("reranker"); assert.equal(rerank.ok, true); assert.equal(rerank.model, "fixture-reranker");
  assert.equal(calls, 2);
  allowed = false;
  const denied = await call("embedder"); assert.equal(denied.ok, false); assert.equal(denied.errorClass, "egress"); assert.equal(calls, 2);
  await secrets.delete({ kind: "owner" }, "fixture");
  assert.ok(!JSON.stringify([embed, rerank, denied]).includes("fixture-key"));
});

test("running core publishes the role probe and enforces schema and human admin identity", async t => {
  const { createCore } = await import("../src/core.ts");
  const { flatTestInternals } = await import("./helpers/flat-embedder.ts");
  const { connect } = await import("./helpers/connect.ts");
  const { writeFileSync } = await import("node:fs");
  const home = tempDir("p1b-role-rpc-"), cfg = defaults(); cfg.agents.fixture = {};
  cfg.engine = { neo: { enabled: false }, gc: { enabled: false }, obsidianBridge: { enabled: false }, merging: { enabled: false }, dreaming: { enabled: false }, skillMiner: { enabled: false }, temporalContext: { enabled: false }, conversationReactivationRecall: { enabled: false } };
  writeFileSync(layout(home).configPath, JSON.stringify(cfg));
  let who = { userId: "fixture", role: "admin", kind: "person" };
  const core = createCore({ home, testInternals: flatTestInternals(), rbac: { resolve: () => who as any } });
  await core.start(); t.after(() => core.stop({ budgetMs: 5000 }));
  const client = await connect({ address: core.address, token: core.token }); t.after(() => client.close());
  const result = await client.call<any>("admin.engine.test", { role: "embedder" }); assert.equal(result.ok, true); assert.ok(result.dimensions > 0);
  assert.equal((await client.call<any>("admin.engine.test", { role: "captioner" })).errorClass, "unsupported");
  await assert.rejects(client.call("admin.engine.test", { role: "embedder", key: "fixture" }), (e: any) => e.error === "E_INVALID_PARAMS");
  who = { ...who, role: "viewer" }; await assert.rejects(client.call("admin.engine.test", { role: "embedder" }), (e: any) => e.error === "E_DENIED");
  who = { ...who, role: "owner", kind: "agent" }; await assert.rejects(client.call("admin.engine.test", { role: "embedder" }), (e: any) => e.error === "E_DENIED");
});
