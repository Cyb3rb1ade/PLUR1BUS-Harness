// Cargo-only dependency changes retain verified npm attribution from its native baseline.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { generateNotices } from "../third-party.mjs";

const SEPARATOR = "\n\n============================================================\n\n";
const sha = (text) => createHash("sha256").update(text).digest("hex");
const shared = "Copyright npm author\nMIT licence\n";
const originalCargo = "Retired crate licence\n";
const currentCargo = "Copyright current crate\nApache-2.0 licence\n";

function fixture(run) {
  const directory = mkdtempSync(join(tmpdir(), "third-party-reuse-"));
  try {
    mkdirSync(join(directory, "apps/desktop"), { recursive: true });
    for (const file of ["pnpm-lock.yaml", "Cargo.lock", "apps/desktop/Cargo.lock"]) {
      writeFileSync(join(directory, file), `locked ${file}\n`);
    }
    const inventory = `# Third-party attribution (generated)\n\nGenerated by scripts/release/third-party.mjs. Runtime npm dependencies installed on darwin-arm64; Cargo locked dependency graphs include target/dev/build dependencies conservatively.\n\n\`\`\`\npnpm-lock.yaml: ${sha(readFileSync(join(directory, "pnpm-lock.yaml")))}\nCargo.lock: ${"a".repeat(64)}\napps/desktop/Cargo.lock: ${"b".repeat(64)}\n\`\`\`\n\n| Ecosystem | Dependency | Version | Licence | Attribution |\n|---|---|---|---|---|\n| cargo | retired | 1.0.0 | MIT | Retired author |\n| npm | @example/native | 2.0.0 | MIT | Alice \\| Team |\n`;
    writeFileSync(join(directory, "THIRD_PARTY.md"), inventory);
    const blocks = [
      `SHA256 ${sha(shared)}\ncargo:retired@1.0.0/LICENSE\nnpm:@example/native@2.0.0/LICENSE\n\n${shared}`,
      `SHA256 ${sha(originalCargo)}\ncargo:retired@1.0.0/NOTICE\n\n${originalCargo}`,
    ];
    writeFileSync(join(directory, "THIRD_PARTY-LICENSES.txt"), blocks.join(SEPARATOR) + "\n");
    const crateDirectory = join(directory, "current-crate");
    mkdirSync(crateDirectory);
    writeFileSync(join(crateDirectory, "Cargo.toml"), "[package]\nname='current'\n");
    writeFileSync(join(crateDirectory, "LICENSE"), currentCargo);
    writeFileSync(join(crateDirectory, "NOTICE"), shared);
    const calls = [];
    const collect = (command, args, cwd) => {
      calls.push({ command, args, cwd });
      assert.equal(cwd, directory);
      if (command === "pnpm") {
        return { MIT: [{ name: "fresh-npm", versions: ["3.0.0"], paths: [crateDirectory], author: "Fresh author" }] };
      }
      assert.equal(command, "cargo");
      assert.ok(args.includes("--locked"));
      return { packages: [
        { name: "current", version: "1.2.0", source: "registry+https://github.com/rust-lang/crates.io-index",
          license: "Apache-2.0", manifest_path: join(crateDirectory, "Cargo.toml"), authors: ["Current author"] },
        { name: "workspace", version: "0.1.0", source: null },
      ] };
    };
    // The injected collector must be used; even a regression must not spawn host package managers.
    const generate = (options = {}) => {
      const oldPath = process.env.PATH;
      process.env.PATH = "";
      try {
        return generateNotices({ directory, collect, reuseNpm: true, ...options });
      } finally {
        if (oldPath === undefined) delete process.env.PATH;
        else process.env.PATH = oldPath;
      }
    };
    run({ directory, inventory, calls, generate });
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

test("npm reuse preserves native rows and original notices while replacing both Cargo graphs", () => {
  fixture(({ generate, calls }) => {
    const output = generate();
    const index = output["THIRD_PARTY.md"];
    const notices = output["THIRD_PARTY-LICENSES.txt"];
    assert.match(index, /installed on darwin-arm64/);
    assert.ok(index.includes("| npm | @example/native | 2.0.0 | MIT | Alice \\| Team |"));
    assert.ok(index.includes("| cargo | current | 1.2.0 | Apache-2.0 | Current author |"));
    assert.doesNotMatch(index, /retired|fresh-npm|workspace \|/);
    assert.ok(notices.includes(`SHA256 ${sha(shared)}\ncargo:current@1.2.0/NOTICE\nnpm:@example/native@2.0.0/LICENSE\n\n${shared}`));
    assert.ok(notices.includes(currentCargo));
    assert.doesNotMatch(notices, /retired|Retired crate/);
    assert.deepEqual(calls.map(({ command, args }) => [command, args.at(-1)]), [
      ["cargo", "Cargo.toml"], ["cargo", "apps/desktop/Cargo.toml"],
    ]);
    assert.deepEqual(generate(), output, "reuse remains deterministic");
  });
});

test("npm reuse refuses a changed lockfile before collecting dependencies", () => {
  fixture(({ directory, generate, calls }) => {
    writeFileSync(join(directory, "pnpm-lock.yaml"), "changed lock\n");
    assert.throws(() => generate(), /pnpm-lock.yaml.*changed|unchanged.*pnpm-lock.yaml/);
    assert.equal(calls.length, 0);
  });
});

test("npm reuse refuses tampered notice text before collecting dependencies", () => {
  fixture(({ directory, generate, calls }) => {
    const file = join(directory, "THIRD_PARTY-LICENSES.txt");
    writeFileSync(file, readFileSync(file, "utf8").replace("MIT licence", "altered licence"));
    assert.throws(() => generate(), /notice.*(?:hash|SHA)|(?:hash|SHA).*notice/i);
    assert.equal(calls.length, 0);
  });
});

test("npm reuse refuses duplicate notice blocks even when their Cargo sources will be replaced", () => {
  fixture(({ directory, generate, calls }) => {
    const file = join(directory, "THIRD_PARTY-LICENSES.txt");
    const full = readFileSync(file, "utf8").slice(0, -1);
    writeFileSync(file, full + SEPARATOR + full.split(SEPARATOR).at(-1) + "\n");
    assert.throws(() => generate(), /duplicate.*notice/i);
    assert.equal(calls.length, 0);
  });
});

test("npm reuse refuses malformed inventories and dangling npm notice references", () => {
  fixture(({ directory, inventory, generate }) => {
    const file = join(directory, "THIRD_PARTY.md");
    writeFileSync(file, inventory.replace("darwin-arm64", "unverified target"));
    assert.throws(() => generate(), /baseline.*(?:platform|provenance)|(?:platform|provenance).*baseline/i);
    writeFileSync(file, inventory + "| npm | broken |\n");
    assert.throws(() => generate(), /baseline.*row|row.*baseline/i);
    writeFileSync(file, inventory.replace("| npm | @example/native | 2.0.0 | MIT | Alice \\| Team |\n", ""));
    assert.throws(() => generate(), /notice.*(?:unknown|missing)|(?:unknown|missing).*notice/i);
  });
});

test("native generation still collects npm metadata and uses the current platform", () => {
  fixture(({ directory, generate, calls }) => {
    writeFileSync(join(directory, "THIRD_PARTY.md"), "invalid baseline ignored in native mode\n");
    const output = generate({ reuseNpm: false });
    assert.match(output["THIRD_PARTY.md"], new RegExp(`installed on ${process.platform}-${process.arch}`));
    assert.ok(output["THIRD_PARTY.md"].includes("| npm | fresh-npm | 3.0.0 | MIT | Fresh author |"));
    assert.deepEqual(calls.map(({ command }) => command), ["pnpm", "cargo", "cargo"]);
  });
});
