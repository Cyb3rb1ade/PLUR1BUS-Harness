// Generated attribution inventory for the installed target. Run on each native
// packaging runner as well as the macOS source-drift gate; never infer missing metadata.
import { spawnSync } from 'node:child_process';
import { readFileSync, readdirSync, existsSync, writeFileSync, realpathSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../../', import.meta.url));
const locks = ['pnpm-lock.yaml', 'Cargo.lock', 'apps/desktop/Cargo.lock'];
const order = (a, b) => a < b ? -1 : a > b ? 1 : 0;
function run(cmd, args) {
  const r = spawnSync(cmd, args, { cwd: root, encoding: 'utf8', maxBuffer: 128 * 1024 * 1024, shell: process.platform === 'win32' && cmd === 'pnpm' });
  if (r.error || r.status !== 0) throw new Error(`cannot collect ${cmd} attribution metadata`);
  return JSON.parse(r.stdout);
}
function notices(dir) {
  return readdirSync(dir, { withFileTypes: true }).filter(d => d.isFile() && /^(licen[cs]e|notice|copying|copyright)(?:[._-].*)?$/i.test(d.name)).sort((a, b) => order(a.name, b.name)).map(d => ({ name: d.name, text: readFileSync(join(dir, d.name), 'utf8').replace(/\r\n/g, '\n') }));
}
export function generateNotices() {
  const rows = new Map(), texts = new Map();
  const add = (ecosystem, name, version, license, dir, author = '') => {
    if (!license) throw new Error(`missing licence: ${ecosystem} ${name}@${version}`);
    rows.set(`${ecosystem}:${name}@${version}`, { ecosystem, name, version, license, author });
    for (const n of notices(dir)) {
      const digest = createHash('sha256').update(n.text).digest('hex');
      if (!texts.has(digest)) texts.set(digest, { text: n.text, sources: [] });
      texts.get(digest).sources.push(`${ecosystem}:${name}@${version}/${n.name}`);
    }
  };
  for (const [license, pkgs] of Object.entries(run('pnpm', ['licenses', 'list', '--prod', '--json']))) for (const p of pkgs) {
    for (const version of p.versions) add('npm', p.name, version, p.license || license, p.paths[0], typeof p.author === 'string' ? p.author : '');
  }
  for (const manifest of ['Cargo.toml', 'apps/desktop/Cargo.toml']) {
    const metadata = run('cargo', ['metadata', '--format-version', '1', '--locked', '--manifest-path', manifest]);
    for (const p of metadata.packages) {
      if (!p.source) continue;
      add('cargo', p.name, p.version, p.license || (p.license_file ? `SEE ${p.license_file}` : null), dirname(p.manifest_path), (p.authors || []).join(', '));
    }
  }
  const hashes = locks.map(p => `${p}: ${createHash('sha256').update(readFileSync(join(root, p))).digest('hex')}`).join('\n');
  const safe = s => String(s).replace(/\|/g, '\\|').replace(/[\r\n]/g, ' ');
  const table = [...rows.values()].sort((a, b) => order(`${a.ecosystem}:${a.name}@${a.version}`, `${b.ecosystem}:${b.name}@${b.version}`)).map(p => `| ${safe(p.ecosystem)} | ${safe(p.name)} | ${safe(p.version)} | ${safe(p.license)} | ${safe(p.author)} |`).join('\n');
  const index = `# Third-party attribution (generated)\n\nGenerated by scripts/release/third-party.mjs. Runtime npm dependencies installed on ${process.platform}-${process.arch}; Cargo locked dependency graphs include target/dev/build dependencies conservatively. Original notices and licence texts are in THIRD_PARTY-LICENSES.txt and the dependency payloads. Python client runtime is stdlib-only. This inventory is attribution, not an advisory or legal-approval result.\n\nRegenerate on each native packaging target; optional native npm packages differ by target. The source drift check uses macOS arm64. Buzz/Nostr and A2A SDK Apache-2.0 notices must be included when those SDKs enter the installed graph; no such SDK dependency is present on this base.\n\n\`\`\`\n${hashes}\n\`\`\`\n\n| Ecosystem | Dependency | Version | Licence | Attribution |\n|---|---|---|---|---|\n${table}\n`;
  const full = [...texts].sort(([a], [b]) => order(a, b)).map(([digest, n]) => `SHA256 ${digest}\n${[...new Set(n.sources)].sort(order).join('\n')}\n\n${n.text}`).join('\n\n============================================================\n\n');
  return { 'THIRD_PARTY.md': index, 'THIRD_PARTY-LICENSES.txt': full + '\n' };
}
function main() {
  const args = process.argv.slice(2), check = args.includes('--check');
  const pos = args.indexOf('--out'); const out = pos < 0 ? root : resolve(args[pos + 1]);
  for (const [file, contents] of Object.entries(generateNotices())) {
    const path = join(out, file);
    if (check) { if (!existsSync(path) || readFileSync(path, 'utf8') !== contents) throw new Error(`${file} is stale; regenerate attribution`); }
    else writeFileSync(path, contents);
  }
}
if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) { try { main(); } catch (e) { console.error(e.message); process.exitCode = 1; } }
