// Generated attribution inventory for the installed target. Run on each native
// packaging runner as well as the macOS source-drift gate; never infer missing metadata.
// --reuse-npm retains hash-verified native npm evidence only when its lockfile is unchanged.
import { spawnSync } from 'node:child_process';
import { readFileSync, readdirSync, existsSync, writeFileSync, realpathSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../../', import.meta.url));
const locks = ['pnpm-lock.yaml', 'Cargo.lock', 'apps/desktop/Cargo.lock'];
const order = (a, b) => a < b ? -1 : a > b ? 1 : 0;
const separator = '\n\n============================================================\n\n';
const tableHeader = '| Ecosystem | Dependency | Version | Licence | Attribution |\n|---|---|---|---|---|\n';
const sha256 = value => createHash('sha256').update(value).digest('hex');
// Texts a dependency needs but does not ship (owner decision 2026-10-28, docs/dependency-policy.md): an LGPL-3.0
// package gets the GNU LGPL and the GPL it incorporates, and sharp's prebuilt libvips packages also the directions
// to their source. They are listed as supplied, so no one takes them for files of the package.
const suppliedDir = fileURLToPath(new URL('./licence-texts/', import.meta.url));
const suppliedTexts = row => !/\bLGPL-3\.0/.test(row.license) ? []
  : ['GPL-3.0.txt', 'LGPL-3.0.txt', ...(/^@img\/sharp-/.test(row.name) ? ['libvips-sources.txt'] : [])];
function run(cmd, args, cwd = root) {
  const r = spawnSync(cmd, args, { cwd, encoding: 'utf8', maxBuffer: 128 * 1024 * 1024, shell: process.platform === 'win32' && cmd === 'pnpm' });
  if (r.error || r.status !== 0) throw new Error(`cannot collect ${cmd} attribution metadata`);
  return JSON.parse(r.stdout);
}
function notices(dir) {
  return readdirSync(dir, { withFileTypes: true }).filter(d => d.isFile() && /^(licen[cs]e|notice|copying|copyright)(?:[._-].*)?$/i.test(d.name)).sort((a, b) => order(a.name, b.name)).map(d => ({ name: d.name, text: readFileSync(join(dir, d.name), 'utf8').replace(/\r\n/g, '\n') }));
}
function baselineRows(index) {
  const parts = index.split(tableHeader);
  if (parts.length !== 2) throw new Error('invalid npm baseline table');
  const rows = new Map();
  for (const line of parts[1].trimEnd().split('\n')) {
    const cells = line.split(/(?<!\\)\|/);
    if (cells.length !== 7 || cells[0] !== '' || cells.at(-1) !== '' ||
        cells.slice(1, -1).some(cell => !cell.startsWith(' ') || !cell.endsWith(' '))) {
      throw new Error('invalid npm baseline row');
    }
    const [ecosystem, name, version, license, author] = cells.slice(1, -1).map(cell => cell.slice(1, -1).replace(/\\\|/g, '|'));
    if (!['npm', 'cargo'].includes(ecosystem) || !name || !version || !license) throw new Error('invalid npm baseline row');
    const id = `${ecosystem}:${name}@${version}`;
    if (rows.has(id)) throw new Error('duplicate npm baseline row');
    rows.set(id, { ecosystem, name, version, license, author });
  }
  return rows;
}

function baselineTexts(full, rows) {
  if (!full.endsWith('\n')) throw new Error('invalid npm baseline notices');
  const texts = new Map();
  const seen = new Set();
  for (const block of full.slice(0, -1).split(separator)) {
    const match = /^SHA256 ([0-9a-f]{64})\n([^\n]+(?:\n[^\n]+)*)\n\n([\s\S]*)$/.exec(block);
    if (!match) throw new Error('invalid npm baseline notice block');
    const [, digest, sources, text] = match;
    if (sha256(text) !== digest) throw new Error('npm baseline notice SHA256 mismatch');
    if (seen.has(digest)) throw new Error('duplicate npm baseline notice hash');
    seen.add(digest);
    const selected = [];
    for (const source of sources.split('\n')) {
      const slash = source.lastIndexOf('/');
      if (slash < 0 || !rows.has(source.slice(0, slash)) || !source.slice(slash + 1)) {
        throw new Error('unknown npm baseline notice reference');
      }
      if (source.startsWith('npm:')) selected.push(source);
    }
    // Cargo sources are recollected from their actual current package directories below.
    if (selected.length) texts.set(digest, { text, sources: selected });
  }
  return texts;
}

function npmBaseline(directory) {
  const index = readFileSync(join(directory, 'THIRD_PARTY.md'), 'utf8').replace(/\r\n/g, '\n');
  const provenance = /^Generated by scripts\/release\/third-party\.mjs\. Runtime npm dependencies installed on ([a-z0-9]+-[a-z0-9]+);/m.exec(index);
  if (!index.startsWith('# Third-party attribution (generated)\n\n') || !provenance) {
    throw new Error('invalid npm baseline platform provenance');
  }
  const recorded = [...index.matchAll(/^pnpm-lock\.yaml: ([0-9a-f]{64})$/gm)];
  if (recorded.length !== 1 || recorded[0][1] !== sha256(readFileSync(join(directory, 'pnpm-lock.yaml')))) {
    throw new Error('--reuse-npm requires unchanged pnpm-lock.yaml against the native baseline');
  }
  const rows = baselineRows(index);
  const full = readFileSync(join(directory, 'THIRD_PARTY-LICENSES.txt'), 'utf8').replace(/\r\n/g, '\n');
  return { platform: provenance[1], rows, texts: baselineTexts(full, rows) };
}

/** Generate current Cargo attribution; npm reuse requires an unchanged lock and verified native evidence. */
export function generateNotices({ reuseNpm = false, directory = root, collect = run } = {}) {
  const baseline = reuseNpm ? npmBaseline(directory) : null;
  const rows = new Map(baseline ? [...baseline.rows].filter(([, row]) => row.ecosystem === 'npm') : []);
  const texts = baseline?.texts ?? new Map();
  const add = (ecosystem, name, version, license, dir, author = '') => {
    if (!license) throw new Error(`missing licence: ${ecosystem} ${name}@${version}`);
    rows.set(`${ecosystem}:${name}@${version}`, { ecosystem, name, version, license, author });
    for (const n of notices(dir)) {
      const digest = createHash('sha256').update(n.text).digest('hex');
      if (!texts.has(digest)) texts.set(digest, { text: n.text, sources: [] });
      texts.get(digest).sources.push(`${ecosystem}:${name}@${version}/${n.name}`);
    }
  };
  if (!reuseNpm) for (const [license, pkgs] of Object.entries(collect('pnpm', ['licenses', 'list', '--prod', '--json'], directory))) for (const p of pkgs) {
    for (const version of p.versions) add('npm', p.name, version, p.license || license, p.paths[0], typeof p.author === 'string' ? p.author : '');
  }
  for (const manifest of ['Cargo.toml', 'apps/desktop/Cargo.toml']) {
    const metadata = collect('cargo', ['metadata', '--format-version', '1', '--locked', '--manifest-path', manifest], directory);
    for (const p of metadata.packages) {
      if (!p.source) continue;
      add('cargo', p.name, p.version, p.license || (p.license_file ? `SEE ${p.license_file}` : null), dirname(p.manifest_path), (p.authors || []).join(', '));
    }
  }
  for (const p of rows.values()) for (const file of suppliedTexts(p)) {
    const text = readFileSync(join(suppliedDir, file), 'utf8').replace(/\r\n/g, '\n');
    const digest = sha256(text);
    if (!texts.has(digest)) texts.set(digest, { text, sources: [] });
    texts.get(digest).sources.push(`${p.ecosystem}:${p.name}@${p.version}/${file} (supplied by the harness)`);
  }
  const hashes = locks.map(p => `${p}: ${sha256(readFileSync(join(directory, p)))}`).join('\n');
  const safe = s => String(s).replace(/\|/g, '\\|').replace(/[\r\n]/g, ' ');
  const table = [...rows.values()].sort((a, b) => order(`${a.ecosystem}:${a.name}@${a.version}`, `${b.ecosystem}:${b.name}@${b.version}`)).map(p => `| ${safe(p.ecosystem)} | ${safe(p.name)} | ${safe(p.version)} | ${safe(p.license)} | ${safe(p.author)} |`).join('\n');
  const platform = baseline?.platform ?? `${process.platform}-${process.arch}`;
  const index = `# Third-party attribution (generated)\n\nGenerated by scripts/release/third-party.mjs. Runtime npm dependencies installed on ${platform}; Cargo locked dependency graphs include target/dev/build dependencies conservatively. Original notices and licence texts are in THIRD_PARTY-LICENSES.txt and the dependency payloads; a text a dependency does not ship itself is supplied from scripts/release/licence-texts/ and marked as supplied. Python client runtime is stdlib-only. This inventory is attribution, not an advisory or legal-approval result.\n\nRegenerate on each native packaging target; optional native npm packages differ by target. The source drift check uses macOS arm64. Buzz/Nostr and A2A SDK Apache-2.0 notices must be included when those SDKs enter the installed graph; no such SDK dependency is present on this base.\n\n\`\`\`\n${hashes}\n\`\`\`\n\n${tableHeader}${table}\n`;
  const full = [...texts].sort(([a], [b]) => order(a, b)).map(([digest, n]) => `SHA256 ${digest}\n${[...new Set(n.sources)].sort(order).join('\n')}\n\n${n.text}`).join(separator);
  return { 'THIRD_PARTY.md': index, 'THIRD_PARTY-LICENSES.txt': full + '\n' };
}
function main() {
  const args = process.argv.slice(2), check = args.includes('--check');
  const pos = args.indexOf('--out'); const out = pos < 0 ? root : resolve(args[pos + 1]);
  for (const [file, contents] of Object.entries(generateNotices({ reuseNpm: args.includes('--reuse-npm') }))) {
    const path = join(out, file);
    if (check) { if (!existsSync(path) || readFileSync(path, 'utf8') !== contents) throw new Error(`${file} is stale; regenerate attribution`); }
    else writeFileSync(path, contents);
  }
}
if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) { try { main(); } catch (e) { console.error(e.message); process.exitCode = 1; } }
