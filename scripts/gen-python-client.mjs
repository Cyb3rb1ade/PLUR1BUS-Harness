// Generator for the Python client (HM2-R3), run by `packages/rpc-schema`'s `gen` script:
//  1. writes clients/python/plur1bus-memory-client/src/plur1bus_memory_client/_schema.py from rpc.schema.json
//     (RPC_VERSION, SCHEMA_SHA256 of the LF-normalised schema bytes, METHODS = {name: (x-server, x-stability, x-since)});
//  2. verifies the hand-committed tests/fixtures/address-vectors.json against module-api's coreAddress and fails on
//     drift. The vectors are never written here (F22): their hashes were computed independently of every
//     implementation, and Python, Rust and TypeScript tests all read the same file.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const clientDir = join(root, "clients", "python", "plur1bus-memory-client");
const schemaPath = join(root, "packages", "rpc-schema", "schema", "rpc.schema.json");
const outPath = join(clientDir, "src", "plur1bus_memory_client", "_schema.py");
const vectorsPath = join(clientDir, "tests", "fixtures", "address-vectors.json");

// A Windows checkout may carry CRLF; the hash is over LF bytes so every OS computes the same value.
const schemaText = readFileSync(schemaPath, "utf8").replaceAll("\r\n", "\n");
const schema = JSON.parse(schemaText);
const sha = createHash("sha256").update(schemaText, "utf8").digest("hex");
const rpc = schema["x-rpc-version"];
if (typeof rpc !== "string" || !/^\d+\.\d+\.\d+$/.test(rpc)) throw new Error("rpc.schema.json: x-rpc-version missing");

const py = (s) => JSON.stringify(s); // ASCII names and versions: a JSON string is a valid Python literal
const rows = Object.keys(schema.$defs.methods)
  .sort()
  .map((name) => {
    const d = schema.$defs.methods[name];
    for (const k of ["x-server", "x-stability", "x-since"]) {
      if (typeof d[k] !== "string") throw new Error(`rpc.schema.json: method ${name} lacks ${k}`);
    }
    return `    ${py(name)}: (${py(d["x-server"])}, ${py(d["x-stability"])}, ${py(d["x-since"])}),`;
  });
const out = [
  '"""Generated by scripts/gen-python-client.mjs from packages/rpc-schema/schema/rpc.schema.json -- do not edit."""',
  "",
  `RPC_VERSION = ${py(rpc)}`,
  `SCHEMA_SHA256 = ${py(sha)}`,
  "",
  "#: method -> (x-server, x-stability, x-since)",
  "METHODS: dict[str, tuple[str, str, str]] = {",
  ...rows,
  "}",
  "",
].join("\n");
writeFileSync(outPath, out);

const { coreAddress } = await import(pathToFileURL(join(root, "packages", "module-api", "src", "paths.ts")).href);
const vectors = JSON.parse(readFileSync(vectorsPath, "utf8"));
const drift = vectors.filter((v) => coreAddress(v.home, v.platform) !== v.address);
for (const v of drift) console.error(`address-vectors.json: ${v.platform} ${JSON.stringify(v.home)}: coreAddress gives ${JSON.stringify(coreAddress(v.home, v.platform))}, vector says ${JSON.stringify(v.address)}`);
if (drift.length) process.exit(1);
console.log(`gen-python-client: _schema.py (rpc ${rpc}, ${rows.length} methods); ${vectors.length} address vectors agree`);
