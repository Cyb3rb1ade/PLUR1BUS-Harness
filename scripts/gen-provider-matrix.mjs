/** Generates only the bounded cache-profile reference in provider-matrix.md from the shared JSON table. */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

const START = "<!-- BEGIN GENERATED CACHE PROFILES -->";
const END = "<!-- END GENERATED CACHE PROFILES -->";

function cell(value) {
  if (value === null || value === undefined) return "undocumented";
  return String(value).replaceAll("|", "\\|").replaceAll("\n", "<br>");
}

function list(values) {
  return values?.length ? values.map(cell).join(", ") : "none listed";
}

function table(headers, rows) {
  return [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`),
  ].join("\n");
}

function affinity(entries) {
  if (!entries.length) return "none listed";
  return entries.map((entry) => {
    const wires = entry.wires ? list(entry.wires) : "all row wires";
    return `${entry.in}: ${entry.field}; max length: ${cell(entry.maxLength)}; wires: ${wires}`;
  }).join("<br>");
}

function ttlTiers(entries) {
  if (!entries.length) return "none selectable (TTL not controllable)";
  return entries.map((entry) => {
    const price = (value) => value === null ? "undocumented" : `${value}×`;
    const wires = entry.wires ? list(entry.wires) : "all row wires";
    return `${entry.ttl}: write ${price(entry.write)}, read ${price(entry.read)}; wires: ${wires}`;
  }).join("<br>");
}

function usageRows(usage) {
  const rows = [
    ["Cache-read usage paths (first present wins)", list(usage.read)],
    ["Cache-write usage paths (first present wins)", list(usage.write)],
    ["Input total includes cache reads/writes", usage.inputIncludesCache],
  ];
  if (usage.miss) rows.push(["Cache-miss usage paths (first present wins)", list(usage.miss)]);
  return rows;
}

function renderProfile(row, index) {
  const facts = [
    ["Provider / platforms", `${row.provider} / ${list(row.platforms)}`],
    ["Model match (normalised id)", `\`${row.match}\``],
    ["Class / mechanism", `${row.class} / ${row.mechanism}`],
    ["Minimum tokens / counts / below-minimum behavior",
      `${row.minTokens} / ${row.minTokensCounts} / ${row.belowMinimum}`],
    ["Max breakpoints / lookback positions / collapse runs",
      `${row.maxBreakpoints} / ${row.lookbackPositions} / ${row.lookbackCollapsesRuns}`],
    ["Selectable TTL / price multiples of base input", ttlTiers(row.ttls)],
    ["Predicted warm window (ms) / TTL wire field", `${cell(row.warmMs)} / ${cell(row.ttlField)}`],
    ["Session affinity", affinity(row.affinity)],
    ...usageRows(row.usage),
    ["Suppress writes / tokenizer family", `${row.suppressWrite} / ${row.tokenizerFamily}`],
    ["Source", row.source],
    ["Verification date / status", `${row.verified} / ${row.status}`],
  ];
  if (row.holdConstant) facts.push(["Hold constant within conversation", list(row.holdConstant)]);
  if (row.notes !== undefined) facts.push(["Notes", row.notes]);
  return `#### ${index + 1}. ${row.id}\n\n${table(["Fact", "Value"], facts)}`;
}

function renderGateway(name, gateway) {
  const facts = [
    ["Slug prefixes → upstream provider", Object.entries(gateway.slugPrefixes).map(([prefix, provider]) => {
      return `${prefix} → ${provider}`;
    }).join("<br>")],
    ["Session affinity", affinity(gateway.affinity)],
    ["Marker locations", list(gateway.markers)],
    ["Marker upstream providers", gateway.markerProviders ? list(gateway.markerProviders) : "undocumented"],
    ["TTL forwarded", gateway.ttlForwarded],
    ...usageRows(gateway.usage),
    ["Source", gateway.source],
    ["Verification date / status", `${gateway.verified} / ${gateway.status}`],
  ];
  if (gateway.notes !== undefined) facts.push(["Notes", gateway.notes]);
  return `#### ${name}\n\n${table(["Gateway fact", "Value"], facts)}`;
}

/** Render a validated cache-profile table as deterministic Markdown; preserves the table's match order and unknowns. */
export function renderProviderMatrix(profiles) {
  const introduction = [
    "Generated by `scripts/gen-provider-matrix.mjs` from `packages/providers/schema/cache-profiles.json`.",
    `Table version: ${profiles.version}. Regenerate with \`pnpm docs:gen\`; verify with \`pnpm docs:check\`.`,
    "Rows and hosts retain source order: the first applicable match wins. Model matches use lower-case IDs,",
    "with gateway prefixes removed and dots replaced by dashes. Aliases map requested IDs to served IDs.",
    "`undocumented` represents null or absent data, never a zero or a guessed default. An unverified",
    "minimum may be a working assumption; read each row's status and notes before relying on it.",
    "Empty TTL lists mean no selectable TTL, not a guaranteed expiry. Zero lookback means none documented.",
    "Usage paths are ordered alternatives. Prices are multiples of base input; wire restrictions remain explicit.",
  ].join("\n");
  const aliases = table(["Requested model", "Served model", "Since", "Source"], profiles.aliases.map((alias) => {
    return [alias.from, alias.to, alias.since, alias.source];
  }));
  const hosts = table(["Host regex (first match wins)", "Gateway", "Vendor", "Platform"], profiles.hosts.map((host) => {
    return [`\`${host.pattern}\``, host.gateway, host.vendor, host.platform];
  }));
  return [
    introduction,
    "### Served-model aliases",
    aliases,
    "### Host routing",
    "Only the listed routing facts are asserted; omitted cells are undocumented, not inferred first-party routes.",
    hosts,
    "### Provider profiles (first match wins)",
    ...profiles.rows.map(renderProfile),
    "### Gateways",
    ...Object.entries(profiles.gateways).map(([name, gateway]) => renderGateway(name, gateway)),
  ].join("\n\n");
}

/** Replace exactly one marked block; refuse missing, duplicated or reversed markers and preserve outside bytes. */
export function updateProviderMatrix(document, profiles) {
  const start = document.indexOf(START);
  const end = document.indexOf(END);
  if (start < 0 || end < start || document.indexOf(START, start + START.length) !== -1
      || document.indexOf(END, end + END.length) !== -1) {
    throw new Error("provider-matrix.md needs exactly one ordered pair of cache-profile generation markers");
  }
  const newline = document.includes("\r\n") ? "\r\n" : "\n";
  const generated = renderProviderMatrix(profiles).replaceAll("\n", newline);
  return document.slice(0, start + START.length)
    + `${newline}${generated}${newline}`
    + document.slice(end);
}

async function main() {
  if (process.argv.slice(2).some((argument) => argument !== "--check")) {
    throw new Error("Usage: node scripts/gen-provider-matrix.mjs [--check]");
  }
  const docPath = new URL("../docs/provider-matrix.md", import.meta.url);
  const dataPath = new URL("../packages/providers/schema/cache-profiles.json", import.meta.url);
  const [document, data] = await Promise.all([readFile(docPath, "utf8"), readFile(dataPath, "utf8")]);
  const updated = updateProviderMatrix(document, JSON.parse(data));
  if (process.argv.includes("--check")) {
    if (updated !== document) {
      throw new Error("docs/provider-matrix.md cache profiles are stale; run pnpm docs:gen");
    }
    return;
  }
  if (updated !== document) await writeFile(docPath, updated);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
