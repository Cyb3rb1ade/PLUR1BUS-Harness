// Writes `crates/plur1bus-core/src/toolcall/first_party_table.rs` from `fixtures/parity/toolcall/tables.json` (P4-K K9b).
//
// The discovery metadata of the shipped tools is assembled in TypeScript from four tables that belong to other packages
// (`first-party-metadata.ts`: the web and file capability rows, the host tool catalogue, hostctl's specs). Until those are
// Rust tables too, the Rust core holds the assembled rows. They are generated from the recorded vector, never typed, and
// `toolcall::vectors` compares every row with the vector, so a change on the TypeScript side fails the replay until this
// script has run again.
//
//   node scripts/parity/toolcall-first-party.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const fixture = fileURLToPath(new URL("../../fixtures/parity/toolcall/tables.json", import.meta.url));
const target = fileURLToPath(new URL("../../crates/plur1bus-core/src/toolcall/first_party_table.rs", import.meta.url));
const rows = JSON.parse(readFileSync(fixture, "utf8")).firstParty;

/** A Rust string literal; the rows are plain ASCII, and anything else stops the generator rather than guess an escape. */
function literal(text) {
  if (!/^[\x20-\x7e]*$/.test(text)) throw new Error(`not printable ASCII: ${JSON.stringify(text)}`);
  return JSON.stringify(text);
}

const lines = [
  "//! Generated by `scripts/parity/toolcall-first-party.mjs` from `fixtures/parity/toolcall/tables.json`; do not edit.",
  "//! Rows are `(name, category, summary, use when, not for)` in the order the TypeScript table was built.",
  "#[rustfmt::skip]",
  "pub(super) const SHIPPED: &[(&str, &str, &str, &str, &str)] = &[",
];
for (const [name, category, summary, useWhen, notFor, kind] of rows) {
  if (kind !== "tool") throw new Error(`${name}: kind ${kind} is not in the Rust table's shape`);
  lines.push(`    (${[name, category, summary, useWhen, notFor].map(literal).join(", ")}),`);
}
lines.push("];", "");
const text = lines.join("\n");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== text) { console.log(`STALE ${target}`); process.exit(1); }
  console.log(`ok    ${target}`);
} else {
  writeFileSync(target, text);
  console.log(`wrote ${target}`);
}
